#!/usr/bin/env bash
# Generate notices for dependencies of every library package and example.
set -euo pipefail
cd "$(dirname "$0")/.."
output=${1:-THIRD_PARTY_LICENSES}
scratch=$(mktemp -d)
trap 'rm -rf "$scratch"' EXIT
cat > "$scratch/go.tmpl" <<'EOF'
{{ range . }}{{ .Name }}	{{ .Version }}	{{ .LicenseName }}	{{ .LicensePath }}
{{ end }}
EOF
GOBIN="$scratch" go install github.com/google/go-licenses/v2@v2.0.1
GOOS=linux GOARCH=amd64 CGO_ENABLED=0 "$scratch/go-licenses" report ./... \
  --ignore github.com/kubebao/openbao-operator-client --template "$scratch/go.tmpl" \
  > "$scratch/go.tsv" 2> "$scratch/go.log" || { cat "$scratch/go.log" >&2; exit 1; }
if grep -q $'\tUnknown\t' "$scratch/go.tsv"; then
  echo "A dependency license could not be identified." >&2
  cat "$scratch/go.tsv" >&2
  exit 1
fi
LC_ALL=C sort -u "$scratch/go.tsv" > "$scratch/sorted.tsv"
{
  cat <<'EOF'
Third-party notices for OpenBao Operator client

Generated by scripts/third-party-licenses.sh (make licenses); do not edit by hand.
The project uses Apache-2.0; see LICENSE and NOTICE.
These notices cover library packages and examples, not development tools.

Go standard library and runtime
License: BSD-3-Clause

EOF
  cat "$(go env GOROOT)/LICENSE"
  while IFS=$'\t' read -r name version license path; do
    [[ -n "$name" ]] || continue
    printf '\n%s %s\nLicense: %s\n\n' "$name" "$version" "$license"
    cat "$path"
  done < "$scratch/sorted.tsv"
} > "$output"
